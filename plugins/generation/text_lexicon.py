def generated_common_rules() -> tuple[tuple[str, tuple[str, ...], str], ...]:
    rules = []
    seen = set()
    for source_action, target_action in ACTION_PAIRS:
        for obj in OBJECTS:
            source = source_action + obj
            if source in seen:
                continue
            seen.add(source)
            rules.append((source, (target_action + obj, "对" + obj + "加以" + target_action), "verb"))
    for source, target in EXTRA_WORD_PAIRS:
        if source not in seen:
            seen.add(source)
            rules.append((source, (target, source + "一些"), "noun"))
    return tuple(rules)
